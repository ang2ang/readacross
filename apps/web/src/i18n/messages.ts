export const translationCatalog: Record<InterfaceLanguage, Record<string, string>> = {
    'zh-CN': chinese,
    en: {},
    ja: japanese,
    fr: french,
    de: german,
    pt: portuguese,
    'zh-TW': traditionalChinese,
};

export function translate(language: InterfaceLanguage, message: string, values: Record<string, string | number> = {}): string {
    const dictionary = translationCatalog[language];
    let text = Object.hasOwn(dictionary, message) ? dictionary[message] : message;
    if (language === 'en' && message === '{count} image(s)') text = Number(values.count) === 1 ? '{count} Image' : '{count} Images';
    if (language === 'en' && message === '{count} image(s) selected') text = Number(values.count) === 1 ? '{count} Image Selected' : '{count} Images Selected';
    return text.replace(/\{(\w+)\}/g, (placeholder, key: string) => Object.hasOwn(values, key) ? String(values[key]) : placeholder);
}

export function localizedLocation(language: InterfaceLanguage, locator?: SourceLocator | null): string {
    if (!locator) return '';
    if (locator.type === 'pdf') return translate(language, 'Page {number}', { number: locator.page });
    return locator.section === undefined ? 'EPUB' : translate(language, 'EPUB · Section {number}', { number: locator.section + 1 });
}
